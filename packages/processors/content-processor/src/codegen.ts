import { relative, resolve, dirname, join } from 'node:path';
import type { ContentEntry } from './types.ts';

function slugToIdentifier(collectionName: string, slug: string): string {
	return `${collectionName}_${slug.replace(/[^a-zA-Z0-9]/g, '_')}`;
}

function serializeEntry(entry: ContentEntry): string {
	return JSON.stringify(entry);
}

function parseEntryTypeImport(entryType: string): { module: string; name: string } {
	const [module, name = 'Entry'] = entryType.split('#');
	if (!module) {
		throw new Error(`Invalid entryType "${entryType}". Expected format: "./path/to/file#TypeName"`);
	}
	return { module, name };
}

export function renderCollectionModule(
	collectionName: string,
	outputDir: string,
	manifest: ContentEntry[],
	entrySources: Array<{ entry: ContentEntry; filePath: string }>,
): string {
	const importLines: string[] = [];
	const componentMapLines: string[] = [];
	const entriesBySlugLines: string[] = [];

	for (const { entry, filePath } of entrySources) {
		const identifier = slugToIdentifier(collectionName, entry.slug);
		const importPath = relative(outputDir, filePath).split('\\').join('/');
		importLines.push(`import ${identifier} from '${importPath}';`);
		componentMapLines.push(`\t'${entry.slug}': ${identifier},`);
	}

	for (const [index, entry] of manifest.entries()) {
		entriesBySlugLines.push(`\t'${entry.slug}': entries[${index}],`);
	}

	return `// This file is auto-generated by @ecopages/content-processor. Do not edit.

import type { EcoComponent } from '@ecopages/core';

${importLines.join('\n')}

export const entries = [
${manifest.map((entry) => `\t${serializeEntry(entry)},`).join('\n')}
] as const;

const entriesBySlug: Record<string, (typeof entries)[number]> = {
${entriesBySlugLines.join('\n')}
};

const componentsBySlug: Record<string, EcoComponent<Record<string, unknown>>> = {
${componentMapLines.join('\n')}
};

export function getEntry(slug: string) {
	const entry = entriesBySlug[slug];
	if (!entry) throw new Error(\`Unknown content entry: \${slug}\`);
	return entry;
}

export function getEntryBySegments(segments: string[]) {
	return getEntry(segments.join('/'));
}

export function getComponent(slug: string): EcoComponent<Record<string, unknown>> {
	const component = componentsBySlug[slug];
	if (!component) throw new Error(\`Unknown content entry: \${slug}\`);
	return component;
}
`;
}

function resolveEntryTypeImport(
	entryType: string,
	rootDir: string,
	typesOutputFile: string,
): { module: string; name: string } {
	const { module, name } = parseEntryTypeImport(entryType);
	const absoluteModule = resolve(rootDir, module);
	const srcDir = join(rootDir, 'src');
	const relativeToSrc = relative(srcDir, absoluteModule).split('\\').join('/');

	if (!relativeToSrc.startsWith('..') && !relativeToSrc.startsWith('/')) {
		return { module: `@/${relativeToSrc}`, name };
	}

	let relativeModule = relative(dirname(typesOutputFile), absoluteModule).split('\\').join('/');
	if (!relativeModule.startsWith('.')) {
		relativeModule = `./${relativeModule}`;
	}
	return { module: relativeModule, name };
}

export function renderCollectionTypesModule(
	collectionName: string,
	entryType?: string,
	typeResolution?: { rootDir: string; typesOutputFile: string },
): string {
	const entryDeclaration = entryType
		? (() => {
				const { module, name } = typeResolution
					? resolveEntryTypeImport(entryType, typeResolution.rootDir, typeResolution.typesOutputFile)
					: parseEntryTypeImport(entryType);
				return `import type { ContentEntry } from '@ecopages/content-processor/types';\n\timport type { ${name} } from '${module}';\n\texport type Entry = ContentEntry<${name}>;`;
			})()
		: `import type { ContentEntry } from '@ecopages/content-processor/types';\n\n\texport type Entry = ContentEntry<Record<string, unknown>>;`;

	return `declare module "ecopages:content/${collectionName}" {
	import type { EcoComponent } from '@ecopages/core';

	${entryDeclaration}

	export const entries: readonly Entry[];
	export function getEntry(slug: string): Entry;
	export function getEntryBySegments(segments: string[]): Entry;
	export function getComponent(slug: string): EcoComponent<Record<string, unknown>>;
}`;
}

export function renderVirtualModuleTypes(
	collections: Record<string, { entryType?: string }>,
	typeResolution?: { rootDir: string; typesOutputFile: string },
): string {
	return `/**
 * Do not edit manually. This file is auto-generated.
 * Virtual module types for ecopages:content/* imports.
 */

${Object.entries(collections)
	.map(([name, definition]) => renderCollectionTypesModule(name, definition.entryType, typeResolution))
	.join('\n\n')}
`;
}
