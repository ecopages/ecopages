import { relative, resolve, dirname, join } from 'node:path';
import type { ContentEntry } from './types.ts';

function serializeEntry(entry: ContentEntry): string {
	return JSON.stringify(entry);
}

function parseEntryTypeImport(entryType: string): { module: string; name: string } {
	const [module, name = 'Entry'] = entryType.split('#');
	if (!module) {
		throw new Error(`Invalid entryType "${entryType}". Expected format: "./path/to/file#TypeName"`);
	}
	return { module, name };
}

/** Emits the shared missing-entry failure used by both generated runtime modules. */
function renderUnknownContentEntryThrow(): string {
	return 'throw HttpError.NotFound(`Unknown content entry: ${slug}`)';
}

/**
 * Generates the metadata-only virtual module for one content collection.
 *
 * @remarks
 * The emitted module intentionally contains no MDX imports. Pages can use its
 * manifest during route preparation without loading entry components.
 */
export function renderCollectionEntriesModule(collectionName: string, manifest: ContentEntry[]): string {
	const entriesBySlugLines: string[] = [];

	for (const [index, entry] of manifest.entries()) {
		entriesBySlugLines.push(`\t'${entry.slug}': entries[${index}],`);
	}

	return `// This file is auto-generated by @ecopages/content-processor. Do not edit.

import { HttpError } from '@ecopages/core/errors';

export const entries = [
${manifest.map((entry) => `\t${serializeEntry(entry)},`).join('\n')}
] as const;

const entriesBySlug: Record<string, (typeof entries)[number]> = {
${entriesBySlugLines.join('\n')}
};

export function getEntry(slug: string) {
	const entry = entriesBySlug[slug];
	if (!entry) ${renderUnknownContentEntryThrow()};
	return entry;
}

export function getEntryBySegments(segments: string[]) {
	return getEntry(segments.join('/'));
}
`;
}

/**
 * Generates the adapter that retains an MDX module's Ecopages component contract.
 *
 * @remarks
 * The loader already attributes identity and live dependency getters. This
 * adapter copies that config by reference onto the callable returned to the
 * route renderer. It does not re-bind or snapshot `config`.
 */
function renderAttachMdxExportsHelper(): string {
	return `type ContentMdxModule = {
	default: EcoComponent<Record<string, unknown>>;
	config?: EcoComponent<Record<string, unknown>>['config'];
	getMetadata?: EcoComponent<Record<string, unknown>>['metadata'];
};

function attachMdxExports(module: ContentMdxModule, sourceFile: string): EcoComponent<Record<string, unknown>> {
	const Page = module.default;
	const component = Object.assign(
		(props: Record<string, unknown>) => Page(props),
		Page,
	) as EcoComponent<Record<string, unknown>>;

	if (module.config) {
		if (!module.config.identity) {
			throw new Error(\`[ecopages] MDX config for "\${sourceFile}" is missing identity; the MDX loader must attribute it.\`);
		}
		component.config = module.config;
	}

	if (module.getMetadata) {
		component.metadata = module.getMetadata;
	}

	return component;
}
`;
}

/** Renders the per-slug MDX import and source-file maps shared by both loaders. */
function renderMdxLoaderMaps(
	outputDir: string,
	entrySources: Array<{ entry: ContentEntry; filePath: string }>,
): string {
	const loaderLines: string[] = [];
	const entrySourceFilesBySlugLines: string[] = [];

	for (const { entry, filePath } of entrySources) {
		const importPath = relative(outputDir, filePath).split('\\').join('/');
		const escapedImportPath = importPath.replace(/'/g, "\\'");
		const sourceFile = filePath.split('\\').join('/');
		const escapedSourceFile = sourceFile.replace(/'/g, "\\'");
		loaderLines.push(`\t'${entry.slug}': () => import('${escapedImportPath}'),`);
		entrySourceFilesBySlugLines.push(`\t'${entry.slug}': '${escapedSourceFile}',`);
	}

	return `const loadersBySlug: Record<string, () => Promise<ContentMdxModule>> = {
${loaderLines.join('\n')}
};

const entrySourceFilesBySlug: Record<string, string> = {
${entrySourceFilesBySlugLines.join('\n')}
};`;
}

/**
 * Generates the server-only virtual module that lazy-loads MDX entries.
 *
 * @remarks
 * The emitted module caches completed components and coalesces concurrent
 * loads for the same slug. `getEntryDependencies` returns the entry Component
 * so collection can resolve assets from identity. Keeping MDX imports here
 * leaves the metadata virtual module cheap to load during route preparation.
 */
export function renderCollectionComponentsModule(
	_collectionName: string,
	outputDir: string,
	entrySources: Array<{ entry: ContentEntry; filePath: string }>,
): string {
	return `// This file is auto-generated by @ecopages/content-processor. Do not edit.

import type { EcoComponent, PageDependenciesResult } from '@ecopages/core';
import { HttpError } from '@ecopages/core/errors';

${renderAttachMdxExportsHelper()}

${renderMdxLoaderMaps(outputDir, entrySources)}

const componentCache = new Map<string, EcoComponent<Record<string, unknown>>>();
const componentLoadPromises = new Map<string, Promise<EcoComponent<Record<string, unknown>>>>();

export async function getComponent(slug: string): Promise<EcoComponent<Record<string, unknown>>> {
	const cached = componentCache.get(slug);
	if (cached) {
		return cached;
	}

	const pending = componentLoadPromises.get(slug);
	if (pending) {
		return pending;
	}

	const load = loadersBySlug[slug];
	if (!load) {
		${renderUnknownContentEntryThrow()};
	}

	const loadPromise = (async () => {
		const module = await load();
		const component = attachMdxExports(module, entrySourceFilesBySlug[slug]!);
		componentCache.set(slug, component);
		return component;
	})().finally(() => {
		componentLoadPromises.delete(slug);
	});

	componentLoadPromises.set(slug, loadPromise);
	return loadPromise;
}

export async function getEntryDependencies(slug: string): Promise<PageDependenciesResult> {
	const component = await getComponent(slug);
	return {
		components: [component],
	};
}
`;
}

/**
 * Generates the browser-only virtual module for one content collection.
 *
 * @remarks
 * Consumers own any synchronous-after-preload cache policy. This module only
 * loads one browser-compiled MDX entry on demand and coalesces concurrent
 * requests; it is not a server renderer.
 */
export function renderCollectionBrowserModule(
	_collectionName: string,
	outputDir: string,
	entrySources: Array<{ entry: ContentEntry; filePath: string }>,
): string {
	return `// This file is auto-generated by @ecopages/content-processor. Do not edit.

import type { EcoComponent } from '@ecopages/core';
import { HttpError } from '@ecopages/core/errors';

${renderAttachMdxExportsHelper()}

${renderMdxLoaderMaps(outputDir, entrySources)}

const componentLoadPromises = new Map<string, Promise<EcoComponent<Record<string, unknown>>>>();

export function loadComponent(slug: string): Promise<EcoComponent<Record<string, unknown>>> {
	const pending = componentLoadPromises.get(slug);
	if (pending) {
		return pending;
	}

	const load = loadersBySlug[slug];
	if (!load) {
		${renderUnknownContentEntryThrow()};
	}

	const loadPromise = load().then((module) => attachMdxExports(module, entrySourceFilesBySlug[slug]!)).finally(() => {
		componentLoadPromises.delete(slug);
	});
	componentLoadPromises.set(slug, loadPromise);
	return loadPromise;
}
`;
}

/**
 * Resolves an app-owned frontmatter type to the specifier used in generated
 * virtual-module declarations.
 *
 * @remarks
 * Types inside `src` use the app's `@/` alias. Types outside it use a relative
 * path from the generated declaration file so TypeScript can resolve both
 * forms without depending on the processor's own location.
 */
function resolveEntryTypeImport(
	entryType: string,
	rootDir: string,
	typesOutputFile: string,
): { module: string; name: string } {
	const { module, name } = parseEntryTypeImport(entryType);
	const absoluteModule = resolve(rootDir, module);
	const srcDir = join(rootDir, 'src');
	const relativeToSrc = relative(srcDir, absoluteModule).split('\\').join('/');

	if (!relativeToSrc.startsWith('..') && !relativeToSrc.startsWith('/')) {
		return { module: `@/${relativeToSrc}`, name };
	}

	let relativeModule = relative(dirname(typesOutputFile), absoluteModule).split('\\').join('/');
	if (!relativeModule.startsWith('.')) {
		relativeModule = `./${relativeModule}`;
	}
	return { module: relativeModule, name };
}

function renderCollectionEntriesTypesModule(
	collectionName: string,
	entryType?: string,
	typeResolution?: { rootDir: string; typesOutputFile: string },
): string {
	const entryDeclaration = entryType
		? (() => {
				const { module, name } = typeResolution
					? resolveEntryTypeImport(entryType, typeResolution.rootDir, typeResolution.typesOutputFile)
					: parseEntryTypeImport(entryType);
				return `import type { ContentEntry } from '@ecopages/content-processor/types';\n\timport type { ${name} } from '${module}';\n\texport type Entry = ContentEntry<${name}>;`;
			})()
		: `import type { ContentEntry } from '@ecopages/content-processor/types';\n\n\texport type Entry = ContentEntry<Record<string, unknown>>;`;

	return `declare module "ecopages:content/${collectionName}" {
	${entryDeclaration}

	export const entries: readonly Entry[];
	/** @throws HttpError 404 when the slug is not in the collection. */
	export function getEntry(slug: string): Entry;
	/** @throws HttpError 404 when no entry matches the segments. */
	export function getEntryBySegments(segments: string[]): Entry;
}`;
}

function renderCollectionComponentsTypesModule(collectionName: string): string {
	return `declare module "ecopages:content/${collectionName}/server" {
	import type { EcoComponent, PageDependenciesResult } from '@ecopages/core';

	/** @throws HttpError 404 when the slug is not in the collection. */
	export function getComponent(slug: string): Promise<EcoComponent<Record<string, unknown>>>;
	/**
	 * Returns { components: [entry] } so collection walks MDX identity.
	 *
	 * @remarks Does not copy config.dependencies or set ownerFile.
	 * Combine Page-local relative assets with mergePageDependencies().
	 * @throws HttpError 404 when the slug is not in the collection.
	 */
	export function getEntryDependencies(slug: string): Promise<PageDependenciesResult>;
}`;
}

function renderCollectionBrowserTypesModule(collectionName: string): string {
	return `declare module "ecopages:content/${collectionName}/browser" {
	import type { EcoComponent } from '@ecopages/core';

	/**
	 * Loads the browser-compiled MDX component for one slug.
	 *
	 * @remarks Use only from the Page Browser Graph.
	 * @throws HttpError 404 when the slug is not in the collection.
	 */
	export function loadComponent(slug: string): Promise<EcoComponent<Record<string, unknown>>>;
}`;
}

/** Generates both ambient virtual-module declarations for one collection. */
export function renderCollectionTypesModule(
	collectionName: string,
	entryType?: string,
	typeResolution?: { rootDir: string; typesOutputFile: string },
): string {
	return `${renderCollectionEntriesTypesModule(collectionName, entryType, typeResolution)}\n\n${renderCollectionComponentsTypesModule(collectionName)}\n\n${renderCollectionBrowserTypesModule(collectionName)}`;
}

/**
 * Generates the declaration file that gives TypeScript types for every
 * configured `ecopages:content/*` virtual module.
 */
export function renderVirtualModuleTypes(
	collections: Record<string, { entryType?: string }>,
	typeResolution?: { rootDir: string; typesOutputFile: string },
): string {
	return `/**
 * Do not edit manually. This file is auto-generated.
 * Virtual module types for ecopages:content/* imports.
 */

${Object.entries(collections)
	.map(([name, definition]) => renderCollectionTypesModule(name, definition.entryType, typeResolution))
	.join('\n\n')}
`;
}
