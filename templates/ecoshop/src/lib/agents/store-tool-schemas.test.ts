import { describe, expect, it } from 'vitest';
import * as z from 'zod/mini';
import { toolsByName } from './store-tool-definitions';

/**
 * The input schemas the pages hand to WebMCP, written from the Zod definitions: each tool's JSON Schema without its
 * `$schema` draft marker.
 */
function generateStoreToolSchemas(): Record<string, unknown> {
	return Object.fromEntries(
		Object.values(toolsByName).map((tool) => {
			const { $schema: _draft, ...schema } = z.toJSONSchema(tool.input, { io: 'input' });
			return [tool.name, schema];
		}),
	);
}

/**
 * The source of `store-tool-schemas.ts` for the given schemas: a TypeScript module, since the dev server serves
 * scripts and not JSON imports.
 */
function storeToolSchemasSource(schemas: Record<string, unknown>): string {
	return [
		'/** Generated by `pnpm schemas` from `store-tool-definitions.ts`; do not edit. */',
		`export const storeToolSchemas = ${JSON.stringify(schemas, null, '\t')};`,
		'',
	].join('\n');
}

describe('store-tool-schemas.ts', () => {
	/**
	 * @remarks
	 * Fails when a Zod definition changed and the committed file did not, or the file was edited by hand. Run
	 * `pnpm schemas` to write it again. The file is kept byte for byte (`.prettierignore`), so the comparison is on text.
	 */
	it('is what z.toJSONSchema writes from the Zod definitions', async () => {
		await expect(storeToolSchemasSource(generateStoreToolSchemas())).toMatchFileSnapshot('./store-tool-schemas.ts');
	});
});
